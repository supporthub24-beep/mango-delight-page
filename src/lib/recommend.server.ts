export async function recommendMangoes(preferences: string, apiKey: string) {
  let runId: string | undefined;
  const provider = createOpenAI({
    baseURL: "https://ai.gateway.lovable.dev/v1",
    apiKey,
    headers: { "Lovable-API-Key": apiKey, "X-Lovable-AIG-SDK": "vercel-ai-sdk" },
    fetch: async (input, init) => {
      const headers = new Headers(init?.headers);
      if (runId) headers.set(RUN_ID, runId);
      const res = await fetch(input, { ...init, headers });
      runId ??= res.headers.get(RUN_ID) ?? undefined;
      return res;
    },
  });

  const result = streamText({
    model: provider.responses("openai/gpt-6-astra"),
    system: `তুমি একটি আমের দোকানের সহকারী। নিচের ভারতীয় বাজার ও জাত-তথ্য ব্যবহার করে গ্রাহকের স্বাদের সঙ্গে মিল খুঁজে দেখো। সুপারিশ করবে কেবল দোকানের তালিকাভুক্ত চারটি আম থেকে ১–২টি; তুলনামূলক জাতগুলো দোকানে আছে বলে বোলো না।
${CATALOG}
উত্তর বাংলায়, সংক্ষেপে (সর্বোচ্চ ৮০ শব্দ)। প্রতিটি সুপারিশের জন্য নাম ও কেন পছন্দের সঙ্গে মানায় তা বলো। ব্যবহারকারী অন্য জাতের নাম বললে তার স্বাদের বৈশিষ্ট্যের সঙ্গে তালিকাভুক্ত আমের মিল ব্যাখ্যা করো, কিন্তু অন্য জাত অর্ডার করার প্রস্তাব দিও না। তালিকার দাম বাংলাদেশি টাকা, ভারতীয় বাজারদর নয়; দাম, বর্তমান প্রাপ্যতা বা মজুত সম্পর্কে দাবি কোরো না। নিশ্চিত নও এমন তথ্য বানিয়ে বলো না। শেষ লাইনে লিখো: IDS: <কমা দিয়ে id গুলো>`,
    prompt: preferences,
    providerOptions: {
      openai: {
        forceReasoning: true,
        reasoningEffort: "low",
        reasoningSummary: "auto",
        store: false,
        include: ["reasoning.encrypted_content"],
      },
    },
  });

  const text = await result.text;
  const match = text.match(/IDS:\s*(.+)\s*$/i);
  const ids = match
    ? (match[1] ?? "").split(",").map((s) => s.trim().toLowerCase()).filter((s) => /^(himsagar|langra|amrapali|fazli)$/.test(s))
    : [];
  return { text: text.replace(/IDS:.*$/i, "").replace(/\*\*/g, "").trim(), ids };
}
